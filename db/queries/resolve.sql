-- At most one row (token_hash is globally UNIQUE). Fixed columns: id, tenant_id,
-- employee_id, revoked_at. revoked_at is returned but NOT filtered -- the
-- revocation decision lives in the domain (CLAUDE.md section 5).
--   SELECT id, tenant_id, employee_id, revoked_at
--   FROM resolve_session_by_token_hash($1);

-- GetInviteByCodeHash (hand-written: internal/db.(*DB).GetInviteByCodeHash, M5-02).
-- Context-less; calls resolve_invite_by_code_hash (00009), never
-- public.employee_invites. At most one row (code_hash is globally UNIQUE). Fixed
-- columns: id, tenant_id, employee_id, expires_at, used_at. expires_at and used_at
-- are returned but NOT filtered -- the data layer carries the truth, the domain
