-- resolve.sql -- THE tenant-resolution path (CLAUDE.md section 4.5, ADR 0002
-- madde 7). This file is the VISIBLE home of the only lookups in the whole
-- codebase that do NOT carry an explicit tenant_id filter, because the tenant is
-- the RESULT of the lookup, not an input: a tap arrives with only a tag uid (from
-- the URL) or a session token hash (from the cookie), an activation with only an
-- invite code hash (from the link) -- none of the three carries a tenant.
--
-- THERE ARE THREE, NOT TWO (M5-02 added GetInviteByCodeHash; ADR 0002 madde 7 was
-- written when there were two and now carries a dated update note). The count was
-- never the guarantee: the ADR's FIVE normative constraints are, and the third
-- lookup meets all five exactly like the first two -- key-only input, at most one
-- row by a globally UNIQUE index, a fixed column list with no SELECT * surface,
-- EXECUTE to tappa_app alone with no cross-tenant table SELECT, and no naive
-- "context is NULL -> show rows" RLS branch. A fourth would have to earn the same.
--
-- ============================================================================
-- WHY THESE TWO ARE HAND-WRITTEN IN Go, NOT GENERATED BY sqlc
-- ============================================================================
-- sqlc v1.28 CANNOT type a call to a `RETURNS TABLE(...)` function. Measured on
-- this exact schema (00003 resolve_session_by_token_hash, 00004 resolve_tag_by_uid):
--
--   * SELECT col, ...  FROM resolve_tag_by_uid(@uid)      -> error: column "uid"
--                                                            does not exist
--   * SELECT * FROM resolve_tag_by_uid(@uid)              -> compiles, but the
--       result type is a single `interface{}` named after the function and the
--       emitted SQL collapses to `SELECT resolve_tag_by_uid FROM ...` (a composite
--       column) -- WRONG at runtime, useless to callers.
--   * SELECT (r).col, ... FROM resolve_tag_by_uid(@uid) r -> a Row struct whose
--       fields are all `interface{}` (Column1..N) -- still untyped, still useless.
--
-- The root cause: sqlc registers column TYPES for `RETURNS SETOF <table>` (it
-- knows the table) but NOT for inline `RETURNS TABLE(a t1, b t2, ...)`. Our
-- functions return a SUBSET of their table's columns, so they must use
-- RETURNS TABLE and cannot be SETOF <table>. Making sqlc happy would require
-- editing the applied 00003/00004 migrations (forbidden: applied migrations are
-- immutable, CLAUDE.md section 6) or bumping the pinned sqlc version (out of
-- scope). Re-measured for 00009's resolve_invite_by_code_hash in M5-02: sqlc
-- v1.28 behaves identically, so the invite lookup is hand-written too.
--
-- The workaround (flagged for the third eye): the lookups are implemented as
-- narrow, typed, hand-written accessors on *db.DB in internal/db/resolve.go. That
-- is also their architecturally correct home -- they run CONTEXT-LESS on the raw
-- pool (NOT through WithTenant / not the tenant-scoped store), since they are what
-- PRODUCES the tenant id. The M1-07 pool.go note already anticipated exactly this
-- ("M1-08 adds a narrow, named resolver accessor that must NOT call set_config").
-- The SQL below is the canonical source of truth mirrored verbatim into the Go
-- const strings; keep the two in sync by hand.
--
-- Structural containment (ADR 0002 madde 7), unchanged by where the SQL lives:
-- both call SECURITY DEFINER functions owned by tappa_resolver (NOLOGIN,
-- BYPASSRLS, NOSUPERUSER, column-level SELECT on exactly these two tables) -- NOT
-- the tables directly. The functions are key-parameterised, return at most one
-- row, expose no SELECT * surface, and have a fixed search_path. tappa_app holds
-- EXECUTE on the functions but no cross-tenant SELECT on the tables. After
-- resolution the caller establishes app.tenant_id and everything else runs
-- tenant-scoped; sys:tenant-mismatch (M3-05) cuts the flow when the tag's tenant
-- and the session's tenant disagree.
--
-- NOTE: these statements deliberately have NO `-- name:` directive, so sqlc skips
-- this file (verified: a directive-less .sql file in the queries dir is ignored)
-- and does not emit the broken interface{} code described above.
-- ============================================================================

