-- resolve.sql -- THE tenant-resolution path (CLAUDE.md section 4.5, ADR 0002
-- madde 7). This file is the VISIBLE home of the only lookups in the whole
-- codebase that do NOT carry an explicit tenant_id filter, because the tenant is
-- the RESULT of the lookup, not an input: a tap arrives with only a tag uid (from
-- the URL) or a session token hash (from the cookie), an activation with only an
-- invite code hash (from the link) -- none of the three carries a tenant.
--
-- THERE ARE FIVE (M5-02 added GetInviteByCodeHash; M6-01 phase A added the two
-- admin ones; ADR 0002 madde 7 was written when there were two and now carries
-- dated update notes). The count was never the guarantee: the ADR's FIVE normative
-- constraints are -- key-only input, a bounded result underwritten by a UNIQUE
-- index, a fixed column list with no SELECT * surface, EXECUTE to tappa_app alone
-- with no cross-tenant table SELECT, and no naive "context is NULL -> show rows"
-- RLS branch. A sixth would have to earn the same.
--
-- ONE CONSTRAINT CHANGES SHAPE FOR ONE OF THEM, and it is written here rather than
-- left for a reader to notice. Constraint (ii) is "AT MOST ONE row". Four of the
-- five keep it, because their key is GLOBALLY unique (tags.uid PK,
-- sessions.token_hash, employee_invites.code_hash, admin_sessions.token_hash).
-- GetAdminByEmail CANNOT: an admin email is unique only WITHIN a tenant, because
-- the same person may own two businesses -- the user decision of 2026-08-02 (one
-- login page, one email, a tenant picker AFTER authentication; migration 00011).
-- Its bound is still STRUCTURAL, just different:
--
--   at most ONE row per tenant -- from the partial UNIQUE index
--   (tenant_id, email) WHERE email IS NOT NULL -- hence at most count(tenants)
--   rows, and never two rows carrying the same tenant_id.
--
-- Everything else about it is unchanged: key-only input, fixed column list, no
-- SELECT * surface, EXECUTE to tappa_app alone, standard NULLIF policy on the
-- table. The BOUND is a property of the index, not of the function body -- which
-- is the point the ADR makes about the other four.
--
-- ============================================================================
-- WHY THESE ARE HAND-WRITTEN IN Go, NOT GENERATED BY sqlc
-- ============================================================================
-- sqlc v1.28 CANNOT type a call to a `RETURNS TABLE(...)` function. Measured on
-- this exact schema (00003 resolve_session_by_token_hash, 00004 resolve_tag_by_uid):
--
--   * SELECT col, ...  FROM resolve_tag_by_uid(@uid)      -> error: column "uid"
--                                                            does not exist
--   * SELECT * FROM resolve_tag_by_uid(@uid)              -> compiles, but the
--       result type is a single `interface{}` named after the function and the
--       emitted SQL collapses to `SELECT resolve_tag_by_uid FROM ...` (a composite
--       column) -- WRONG at runtime, useless to callers.
--   * SELECT (r).col, ... FROM resolve_tag_by_uid(@uid) r -> a Row struct whose
--       fields are all `interface{}` (Column1..N) -- still untyped, still useless.
--
-- The root cause: sqlc registers column TYPES for `RETURNS SETOF <table>` (it
-- knows the table) but NOT for inline `RETURNS TABLE(a t1, b t2, ...)`. Our
-- functions return a SUBSET of their table's columns, so they must use
-- RETURNS TABLE and cannot be SETOF <table>. Making sqlc happy would require
-- editing the applied 00003/00004 migrations (forbidden: applied migrations are
-- immutable, CLAUDE.md section 6) or bumping the pinned sqlc version (out of
-- scope). Re-measured for 00009's resolve_invite_by_code_hash in M5-02: sqlc
-- v1.28 behaves identically, so the invite lookup is hand-written too.
-- Re-measured AGAIN for 00011's resolve_admin_by_email in M6-01 phase A, on this
-- exact schema: the explicit column list gives `column "id" does not exist`, and
-- `SELECT *` compiles to `SELECT resolve_admin_by_email FROM ...` returning
-- []interface{}. Unchanged behaviour, so the two admin lookups are hand-written as
-- well.
--
-- The workaround (flagged for the third eye): the lookups are implemented as
-- narrow, typed, hand-written accessors on *db.DB in internal/db/resolve.go. That
-- is also their architecturally correct home -- they run CONTEXT-LESS on the raw
-- pool (NOT through WithTenant / not the tenant-scoped store), since they are what
-- PRODUCES the tenant id. The M1-07 pool.go note already anticipated exactly this
-- ("M1-08 adds a narrow, named resolver accessor that must NOT call set_config").
-- The SQL below is the canonical source of truth mirrored verbatim into the Go
-- const strings; keep the two in sync by hand.
--
-- Structural containment (ADR 0002 madde 7), unchanged by where the SQL lives:
-- both call SECURITY DEFINER functions owned by tappa_resolver (NOLOGIN,
-- BYPASSRLS, NOSUPERUSER, column-level SELECT on exactly these two tables) -- NOT
-- the tables directly. The functions are key-parameterised, return at most one
-- row, expose no SELECT * surface, and have a fixed search_path. tappa_app holds
-- EXECUTE on the functions but no cross-tenant SELECT on the tables. After
-- resolution the caller establishes app.tenant_id and everything else runs
-- tenant-scoped; sys:tenant-mismatch (M3-05) cuts the flow when the tag's tenant
-- and the session's tenant disagree.
--
-- NOTE: these statements deliberately have NO `-- name:` directive, so sqlc skips
-- this file (verified: a directive-less .sql file in the queries dir is ignored)
-- and does not emit the broken interface{} code described above.
-- ============================================================================

-- GetTagByUID (hand-written: internal/db.(*DB).GetTagByUID). Context-less; calls
-- resolve_tag_by_uid (00004), never public.tags. At most one row (uid is PK).
-- Fixed columns: uid, tenant_id, location_id, aes_key_ref, last_ctr, status.
--   SELECT uid, tenant_id, location_id, aes_key_ref, last_ctr, status
--   FROM resolve_tag_by_uid($1);

-- GetEmployeeBySessionHash (hand-written: internal/db.(*DB).GetEmployeeBySessionHash).
-- Context-less; calls resolve_session_by_token_hash (00003), never public.sessions.
-- At most one row (token_hash is globally UNIQUE). Fixed columns: id, tenant_id,
-- employee_id, revoked_at. revoked_at is returned but NOT filtered -- the
-- revocation decision lives in the domain (CLAUDE.md section 5).
--   SELECT id, tenant_id, employee_id, revoked_at
--   FROM resolve_session_by_token_hash($1);

-- GetInviteByCodeHash (hand-written: internal/db.(*DB).GetInviteByCodeHash, M5-02).
-- Context-less; calls resolve_invite_by_code_hash (00009), never
-- public.employee_invites. At most one row (code_hash is globally UNIQUE). Fixed
-- columns: id, tenant_id, employee_id, expires_at, used_at. expires_at and used_at
-- are returned but NOT filtered -- the data layer carries the truth, the domain
-- decides, and the ATOMIC single-use enforcement is a separate statement
-- (store.ConsumeInviteAndActivate; reading used_at here and writing later is the TOCTOU race
-- CLAUDE.md section 4.4 forbids). code_hash is the input and is never returned
-- (section 4.7); neither is the code, which the database never sees at all.
--   SELECT id, tenant_id, employee_id, expires_at, used_at
--   FROM resolve_invite_by_code_hash($1);

-- GetAdminByEmail (hand-written: internal/db.(*DB).GetAdminByEmail, M6-01 phase A).
-- Context-less; calls resolve_admin_by_email (00011), never public.admin_users.
-- N ROWS -- one per tenant this email is an admin of (see the bound above); an
-- unknown email yields ZERO rows and NOT an error, because zero is an ordinary
-- cardinality for a set-returning lookup. Fixed columns: id, tenant_id,
-- password_hash, status.
--   * password_hash is returned because verifying a password is the ONLY reason
--     this lookup must run before a tenant context exists.
--   * status is returned but NOT filtered (the sessions.revoked_at principle): a
--     disabled admin resolves and the caller refuses -- otherwise a disabled
--     account is indistinguishable from a typo and the attempt is unattributable
--     (section 4.6). CreateAdminSession refuses independently, in SQL.
--   * role, full_name, created_at and last_login_at are NOT returned: nothing reads
--     them before the tenant context exists. The tenant PICKER needs the BUSINESS
--     NAME, which this function deliberately does not touch (`tenants` would be a
--     second table on the bypass surface, and a pre-authentication tenant name is
--     itself an enumeration signal) -- so the picker does one tenant-scoped read
--     per candidate (GetAdminForTenantChoice), and role comes with it.
--   * email is the INPUT and is never returned.
-- The $1::citext cast is EXPLICIT AND INTENT-REVEALING, not required -- and the
-- difference was measured, because the earlier wording here claimed "required".
-- Mutation: the accessor's SQL was changed to a bare $1 and every
-- TestGetAdminByEmail* case stayed GREEN (the whole internal/db package did),
-- because pgx sends an untyped text parameter that Postgres coerces to the
-- function's citext parameter on its own. The cast is kept as hygiene: it says at
-- the call site which type this argument is being read as, and it stops a future
-- overload or a driver-level type inference change from silently picking a
-- different one. The case-insensitive comparison itself happens INSIDE the
-- function, with a SCHEMA-QUALIFIED operator (00011 documents the measured trap --
-- under a pinned search_path a bare `=` on citext silently degrades to
-- case-SENSITIVE text equality).
--
-- THIS LOOKUP IS AN EMAIL-ENUMERATION ORACLE BY CONSTRUCTION and cannot be made
-- otherwise in the database: authentication must find the identity before it can
-- verify anything. Closing it is the phase-B handler's obligation -- identical
-- response for unknown email / wrong password / disabled admin, a DUMMY bcrypt
-- comparison when zero rows come back (bcrypt is slow; skipping it is a timing
-- oracle), rate limiting, and an audit_log row for failures.
--
-- IT IS ALSO A COST AMPLIFIER, which is a SEPARATE limit from the oracle and is
-- the fourth phase-B obligation (00011, "PHASE B OBLIGATION 4"). N rows means N
-- bcrypt comparisons, and the expense is entirely on the caller's side of this
-- line. Measured on this schema: an address planted in 500 tenants resolves 500
-- rows in ~0.9-1.2 ms warm (2.8 ms cold) -- the DATABASE IS NOT THE BOTTLENECK --
-- while a cost-10 bcrypt comparison is ~60-100 ms, so ONE unauthenticated
-- POST /login costs ~30-50 s of CPU: roughly 500x amplification from a single
-- credential-less request. Not exploitable today (no APPLICATION path creates a
-- tenant: no CreateTenant/InsertTenant query in db/queries, and no INSERT INTO
-- tenants outside test/fixtures/seed.sql and test helpers), but M7-02's sign-up
-- wizard is PUBLIC and RLS does not stop a tenant from writing ANY email into its
-- OWN admin_users -- from then on the attacker controls the row count. Options,
-- to be CHOSEN in phase B against its own measurement and deliberately not chosen
-- here: cap the candidates one request will verify · stop at the first match ·
-- require email verification before an admin row is resolvable (M7-02). READ THAT
-- MIDDLE OPTION TOGETHER WITH THE NEXT PARAGRAPH -- it collides with it.
--
-- AND IT CANNOT BIND A CANDIDATE TO THE PASSWORD THAT VERIFIED -- the FIFTH phase-B
-- obligation (00011, "PHASE B OBLIGATION 5"), the heaviest of the five and the only
-- one that is a CROSS-TENANT AUTHENTICATION BYPASS (section 4.5) rather than an
-- enumeration signal or a DoS bound: THE SESSION IS ISSUED ONLY TO THE CANDIDATE
-- WHOSE HASH MATCHED, AND THE PICKER SHOWS ONLY MATCHED CANDIDATES.
-- Nothing in this file or in admins.sql can enforce it. This lookup returns a SET;
-- CreateAdminSession never sees a password and asks only that (admin_user_id,
-- tenant_id) be internally consistent and the admin active -- which is exactly what
-- a picker returns, built from REAL rows, so the INSERT ... SELECT guard, the
-- explicit tenant predicate and the RLS WITH CHECK are all satisfied.
-- THE ATTACK (from M7-02, measured live on this schema): the attacker signs up a
-- tenant with the PUBLIC wizard and writes the VICTIM'S EMAIL, under a password
-- they know, into their OWN admin_users -- RLS permits it, it is their tenant. The
-- address then resolves TWO candidates; the password matches the ATTACKER'S row;
-- the picker asks "which business?" and the attacker picks the VICTIM'S:
--   -- C1: only AttackerCo's hash verified; the picker offers VictimCo
--   INSERT ... WHERE a.id='aaaa...0001' AND a.tenant_id='1111...1111'  -- VICTIM
--                AND a.status='active'          -> INSERT 0 1
--   -- C2: every following request passes as well
--                                               -> UPDATE 1 | role=owner
--                                                  | full_name=Victim Owner
-- TENSION WITH OBLIGATION 4, written down because the two pull opposite ways and
-- nothing said so: "stop at the first match" is a fair answer to the bcrypt DoS,
-- but as "stop at the first match AND let the picker list every candidate" it IS
-- the bypass above. Whatever bounds the work, THE SET THE PICKER OFFERS MUST NEVER
-- BE WIDER THAN THE SET WHOSE HASH ACTUALLY VERIFIED.
--   SELECT id, tenant_id, password_hash, status
--   FROM resolve_admin_by_email($1::citext);

-- GetAdminSessionByTokenHash (hand-written:
-- internal/db.(*DB).GetAdminSessionByTokenHash, M6-01 phase A). Context-less; calls
-- resolve_admin_session_by_token_hash (00011), never public.admin_sessions. At most
-- one row (token_hash is globally UNIQUE). Fixed columns: id, tenant_id,
-- admin_user_id, revoked_at. revoked_at is returned but NOT filtered -- the same
-- principle as the employee session lookup. The admin's STATUS is deliberately not
-- joined in: the authoritative liveness test is store.TouchAdminSession, which
-- refuses a revoked session AND a disabled admin in one tenant-scoped statement, so
-- the bypass surface here stays at a single table.
--
-- WHY A RESOLVER AND NOT A TENANT ID IN THE COOKIE. Measured as tappa_app with no
-- context: a direct SELECT on admin_sessions by token_hash returns 0 rows (FORCE
-- RLS, fail-closed). The alternative -- carry the tenant in a signed cookie -- was
-- rejected for the M5-03 reason: tenant is the OUTPUT of resolution, never an
-- input, and a middleware that accepts one lets the caller name its own tenant. A
-- signature proves WE minted the value, not WHICH session it belongs to.
--   SELECT id, tenant_id, admin_user_id, revoked_at
--   FROM resolve_admin_session_by_token_hash($1);
